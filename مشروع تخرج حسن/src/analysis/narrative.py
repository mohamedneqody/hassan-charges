_VERBS = {
    "rose": ("rose", "ارتفع"),
    "fell": ("fell", "انخفض"),
    "stable": ("stayed stable", "استقر"),
}
_QUALIFIERS = {
    "improving": ("an improvement in", "تحسن"),
    "declining": ("a decline in", "تراجع"),
    "stable": ("the stability of", "استقرار"),
}


def _meaning(key: str) -> str:
    en, ar = _MEANINGS.get(key, ("this metric", "هذا المؤشر"))
    return ar if _is_ar() else en


def _ar_name(row) -> str:
    from src.analysis.comparison import LABELS_AR
    return LABELS_AR.get(row.key, row.label) if _is_ar() else row.label


def _comment_for_row(row, prev_value: str, curr_value: str) -> str:
    """One- or two-line hedged comment for a two-year metric row.

    The metric name is rendered separately by the UI ("Name: comment").
    """
    direction = "rose" if row.change > 0 else ("fell" if row.change < 0 else "stable")
    verb_en, verb_ar = _VERBS[direction]
    qual_en, qual_ar = _QUALIFIERS.get(row.trend, _QUALIFIERS["stable"])
    meaning = _meaning(row.key)
    if _is_ar():
        return f"{verb_ar} من {prev_value} إلى {curr_value}، مما قد يشير إلى {qual_ar} {meaning}."
    return f"{verb_en} from {prev_value} to {curr_value}, which may indicate {qual_en} {meaning}."


def _comment_for_growth(row, prev_year: int, curr_year: int) -> str:
    value = f"{'+' if (row.current or 0) > 0 else ''}{row.current:.1f}%"
    meaning = _meaning(row.key)
    if _is_ar():
        tone = "تحسن" if row.current > 0 else ("تراجع" if row.current < 0 else "استقرار")
        return f"بلغ نمو الفترة {value} بين عامي {prev_year} و{curr_year}، مما قد يشير إلى {tone} في {meaning}."
    tone = "an improvement in" if row.current > 0 else ("a decline in" if row.current < 0 else "the stability of")
    return f"growth reached {value} over {prev_year}-{curr_year}, which may indicate {tone} {meaning}."


