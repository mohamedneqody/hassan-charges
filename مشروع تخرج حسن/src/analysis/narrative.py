# Guideline levels that may be cited as evidence (labeled as general).
_GUIDELINES: dict[str, tuple[str, str]] = {
    "current_ratio": ("مقابل مستوى إرشادي عام 2.00x", "vs the 2.00x general guideline"),
    "quick_ratio": ("مقابل مستوى إرشادي عام 1.00x", "vs the 1.00x general guideline"),
    "debt_to_equity": ("مقابل مستوى إرشادي عام أقل من 1.00x", "vs the <1.00x general guideline"),
    "debt_ratio": ("مقابل مستوى إرشادي عام أقل من 0.50x", "vs the <0.50x general guideline"),
    "net_margin": ("مقابل مستوى إرشادي عام 15%", "vs the 15% general guideline"),
}


def _evidence(row, fmt_value, fmt_signed_pct) -> str:
    """Evidence string: metric name + both values + relative change (+guideline)."""
    kind = row.kind
    prev_s = fmt_value(row.previous, kind, "$")
    curr_s = fmt_value(row.current, kind, "$")
    change = fmt_signed_pct(row.change_pct)
    name = _ar_name(row)
    if _is_ar():
        text = f"{name}: من {prev_s} إلى {curr_s} ({change})"
        guideline = _GUIDELINES.get(row.key)
        if guideline:
            text += f"، {guideline[0]}"
        return text
    text = f"{name}: from {prev_s} to {curr_s} ({change})"
    guideline = _GUIDELINES.get(row.key)
    if guideline:
        text += f", {guideline[1]}"
    return text


def build_recommendations(results: dict) -> list[tuple[str, str]]:
    """3-5 evidence-backed recommendations (action, evidence).

    Drivers: the biggest declining and improving metrics by |change %|, each
    carrying its exact values as evidence; topped up with data-backed pads.
    """
    from src.dashboard.charts import fmt_signed_pct, fmt_value

    moving = [
        r for r in results["rows"]
        if r.change_pct is not None and r.change_pct != 0 and r.previous is not None
    ]
    declining = sorted(
        (r for r in moving if r.status == "Negative"),
        key=lambda r: abs(r.change_pct), reverse=True,
    )[:2]
    improving = sorted(
        (r for r in moving if r.status == "Positive"),
        key=lambda r: r.change_pct, reverse=True,
    )[:2]

    recs: list[tuple[str, str]] = []
    for r in declining:
        hint = _ACTIONS_DECLINING.get(r.key)
        action = (
            hint[0] if hint
            else f"معالجة أسباب تراجع {r.label} ومراقبتها ضمن التقارير الشهرية."
            if _is_ar()
            else f"Address the decline in {r.label} and track it in monthly reporting."
        )
        recs.append((action, _evidence(r, fmt_value, fmt_signed_pct)))
    for r in improving:
        hint = _ACTIONS_IMPROVING.get(r.key)
        action = (
            hint[0] if hint
            else f"ترسيخ تحسن {r.label} والمحافظة عليه."
            if _is_ar()
            else f"Consolidate and sustain the improvement in {r.label}."
        )
        recs.append((action, _evidence(r, fmt_value, fmt_signed_pct)))

    # Data-backed pads (only when the evidence actually exists)
    by_key = results.get("rows_by_key", {})
    wc = by_key.get("working_capital")
    if wc is not None and wc.current is not None:
        action = (
            "إدارة رأس المال العامل بمراجعة دورية لأرصدة العملاء والمخزون والموردين."
            if _is_ar()
            else "Manage working capital with a monthly review of receivables, inventory and payables."
        )
        evidence = (
            f"رأس المال العامل: من {fmt_value(wc.previous, 'currency', '$')} "
            f"إلى {fmt_value(wc.current, 'currency', '$')} ({fmt_signed_pct(wc.change_pct)})"
            if _is_ar()
            else f"Working Capital: from {fmt_value(wc.previous, 'currency', '$')} "
                 f"to {fmt_value(wc.current, 'currency', '$')} ({fmt_signed_pct(wc.change_pct)})"
        )
        recs.append((action, evidence))
    cogs = by_key.get("cogs_pct")
    if cogs is not None and cogs.change_pct not in (None, 0):
        action = (
            "ربط أي قرار تسعيري أو شرائي باتجاه نسبة تكلفة المبيعات من الإيراد."
            if _is_ar()
            else "Tie pricing and purchasing decisions to the COGS-to-revenue ratio trend."
        )
        evidence = _evidence(cogs, fmt_value, fmt_signed_pct)
        recs.append((action, evidence))

    return recs[:5]


def _recommendations(results: dict) -> list[tuple[str, str]]:
    return build_recommendations(results)


def build_fallback_narrative(results: dict, base: AIAnalysis) -> AIAnalysis:
    """Fill the per-ratio comments + recommendations from computed metrics."""
    from src.dashboard.charts import fmt_value

    comments: list[tuple[str, str]] = []
    for row in results["growth_rows"]:
        if row.current is None:
            continue
        comments.append(
            (row.label_ar or row.label, _comment_for_growth(row, results["prev_year"], results["curr_year"]))
        )
    for row in results["rows"]:
        if row.previous is None or row.current is None:
            continue  # skip metrics that cannot have a direction
        comments.append(
            (
                row.label_ar or row.label,
                _comment_for_row(
                    row,
                    fmt_value(row.previous, row.kind,
                              ("ج.م" if _is_ar() else "$")),
                    fmt_value(row.current, row.kind,
                              ("ج.م" if _is_ar() else "$")),
                ),
            )
        )

    return AIAnalysis(
        ok=False,
        ratio_comments=comments,
        recommendations=_recommendations(results),
        error=base.error,
        model=base.model,
    )
