# -*- coding: utf-8 -*-
"""حزمة أدلة المصدر للمعاينة (المهمة 7): embeds the REAL review-packet
crops + downscaled page renders + bbox rectangles into a standalone JS
bundle the design preview's Source-Evidence modal shows — the actual
pixels the machine read, not a placeholder. No GT values are exposed
(crops and geometry only), consistent with the reviewer-view rule."""
from __future__ import annotations

import base64
import io
import json
import sys
from pathlib import Path

PROJ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(PROJ))

from PIL import Image  # noqa: E402

QUEUE = PROJ / "cell_evidence/review_queue.json"
OUT = PROJ / "design" / "evidence_bundle.js"
PAGE_WIDTH = 760          # downscaled page render width
MAX_CROP_WIDTH = 420      # crop shown at readable size


def b64_png(img: Image.Image) -> str:
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode("ascii")


def _readings_brief(readings) -> list[str]:
    """readings may be a list or a dict of layer->reading — brief strings."""
    if isinstance(readings, dict):
        return [f"{k}: {v}" for k, v in list(readings.items())[:4]]
    return [str(r) for r in (readings or [])][:4]


def main() -> dict:
    packets = json.loads(QUEUE.read_text(encoding="utf-8"))
    entries: dict[str, dict] = {}
    page_cache: dict[str, str] = {}

    for pk in packets:
        crop_path = PROJ / pk["crop_image"]
        page_path = PROJ / pk["page_image"]
        if not (crop_path.exists() and page_path.exists()):
            continue
        crop = Image.open(crop_path)
        if crop.width > MAX_CROP_WIDTH:
            crop = crop.resize(
                (MAX_CROP_WIDTH, int(crop.height * MAX_CROP_WIDTH
                                    / crop.width)))
        key = f"{pk['field']}|{pk['year']}"
        page_key = str(pk["page"])
        if page_key not in page_cache:
            page = Image.open(page_path)
            page = page.resize((PAGE_WIDTH, int(
                page.height * PAGE_WIDTH / page.width)))
            page_cache[page_key] = b64_png(page)
        entries[key] = {
            "page": pk["page"],
            "year": pk["year"],
            "field": pk["field"],
            "label_text": pk.get("label_text", ""),
            "status": pk.get("status", ""),
            "bbox_rel": pk.get("bbox_rel"),   # [x0,y0,x1,y1] fractions
            "crop_b64": b64_png(crop),
            "crop_sha256": (pk.get("crop_sha256") or "")[:16],
            "page_sha256": (pk.get("page_image_sha256") or "")[:16],
            "readings": _readings_brief(pk.get("readings")),
        }

    js = ("// Auto-generated by tools/build_evidence_bundle.py — do not edit.\n"
          "// REAL review-packet evidence: crops + page renders + bbox.\n"
          "const EVIDENCE = "
          + json.dumps(entries, ensure_ascii=False) + ";\n"
          "const PAGES = " + json.dumps(page_cache) + ";\n")
    OUT.write_text(js, encoding="utf-8")
    print(f"entries: {len(entries)} | pages: {sorted(page_cache)} | "
          f"bundle: {OUT.stat().st_size} bytes -> {OUT.name}")
    return {"entries": len(entries), "out": str(OUT)}


if __name__ == "__main__":
    main()
